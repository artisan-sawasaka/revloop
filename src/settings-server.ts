import { createServer, type IncomingMessage } from 'node:http';
import { randomBytes } from 'node:crypto';
import { spawn } from 'node:child_process';
import { settingsPage } from './settings-page.js';
import { codexModels, readSettings, revisionOf, saveSettings, settingsFile, validateSettings, requireModelChoice, type ModelChoice } from './settings.js';

async function jsonBody(req: IncomingMessage): Promise<unknown> {
  if (req.headers['content-type']!=='application/json') throw Error('Expected application/json');
  const chunks: Buffer[]=[]; let length=0;
  for await (const chunk of req) { length+=chunk.length; if(length>16_384)throw Error('Request too large'); chunks.push(Buffer.from(chunk)); }
  return JSON.parse(Buffer.concat(chunks).toString('utf8'));
}
export async function startSettingsServer(cwd: string, options: {file?:string; models?:()=>Promise<ModelChoice[]>; idleMs?:number}={}) {
  const file=options.file??settingsFile(), token=randomBytes(32).toString('hex'), nonce=randomBytes(24).toString('base64');
  const getModels=options.models??(()=>codexModels(cwd));
  let origin='', timer: ReturnType<typeof setTimeout>;
  const close=()=>{clearTimeout(timer);server.close();server.closeAllConnections();};
  const touch=()=>{clearTimeout(timer);timer=setTimeout(close,options.idleMs??15*60_000);};
  const server=createServer(async(req,res)=>{
    res.setHeader('Cache-Control','no-store');res.setHeader('X-Content-Type-Options','nosniff');res.setHeader('Referrer-Policy','no-referrer');
    res.setHeader('Content-Security-Policy',`default-src 'none'; script-src 'nonce-${nonce}'; style-src 'unsafe-inline'; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'`);
    const send=(code:number,value:unknown)=>{res.writeHead(code,{'Content-Type':'application/json; charset=utf-8'});res.end(JSON.stringify(value));};
    if(req.headers.host!==origin.slice(7)|| (req.headers.origin && req.headers.origin!==origin)) {send(403,{error:'Forbidden origin'});return;}
    if(req.method==='GET'&&req.url==='/'){res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(settingsPage.replace('<script>',`<script nonce="${nonce}">`));return;}
    if(req.headers.authorization!==`Bearer ${token}`){send(403,{error:'Forbidden'});return;}
    touch();
    try {
      if(req.url==='/api/settings'&&req.method==='GET') {
        const settings=await readSettings(file); let models:ModelChoice[]=[],catalogError=false;
        try{models=await getModels();}catch{catalogError=true;}
        send(200,{settings,revision:revisionOf(settings),path:file,models,catalogError});
      } else if(req.url==='/api/settings'&&req.method==='PUT') {
        const body=await jsonBody(req) as {settings?:unknown;revision?:unknown};
        if(!body||typeof body.revision!=='string')throw Error('Missing settings revision');
        const settings=validateSettings(body.settings);
        requireModelChoice(settings.codex,await getModels());
        await saveSettings(settings,body.revision,file);
        send(200,{settings,revision:revisionOf(settings)});
      } else if(req.url==='/api/close'&&req.method==='POST') {send(200,{closed:true});setTimeout(close,100);}
      else send(404,{error:'Not found'});
    } catch(e) { send(400,{error:(e as Error).message}); }
  });
  server.requestTimeout=10_000; server.headersTimeout=10_000;
  await new Promise<void>((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',()=>{server.off('error',reject);resolve();});});
  const address=server.address();if(!address||typeof address==='string')throw Error('No local settings address');
  origin=`http://127.0.0.1:${address.port}`;touch();
  return {url:`${origin}/#${token}`,close,server};
}
export function openSettingsBrowser(url: string): void {
  // URL is generated by our loopback server, never interpreted as shell code.
  if (!/^http:\/\/127\.0\.0\.1:\d+\/#\w+$/.test(url))throw Error('Invalid settings URL');
  const child=process.platform==='win32'
    ? spawn('powershell.exe',['-NoProfile','-NonInteractive','-Command','Start-Process -FilePath $env:REVLOOP_SETTINGS_URL -WindowStyle Hidden'],{env:{...process.env,REVLOOP_SETTINGS_URL:url},stdio:'ignore',windowsHide:true})
    : spawn(process.platform==='darwin'?'open':'xdg-open',[url],{stdio:'ignore'});
  child.on('error',()=>{});child.unref();
}
export async function launchSettings(cli: string,cwd: string,openBrowser=true): Promise<{url:string;settingsFile:string}> {
  return new Promise((resolve,reject)=>{
    const child=spawn(process.execPath,[cli,'settings','--serve','--root',cwd],{cwd,stdio:['ignore','ignore','ignore','ipc'],detached:true,windowsHide:true});
    const timer=setTimeout(()=>{child.kill();reject(Error('Settings GUI startup timed out'));},15_000);
    child.once('error',e=>{clearTimeout(timer);reject(e);});
    child.once('exit',()=>{clearTimeout(timer);reject(Error('Settings GUI exited before startup'));});
    child.once('message',(value:unknown)=>{
      clearTimeout(timer);
      const data=value as {url?:string;error?:string};
      if(!data.url){child.kill();reject(Error(data.error??'Settings GUI did not return a URL'));return;}
      child.disconnect();child.unref();
      if(openBrowser)openSettingsBrowser(data.url);
      resolve({url:data.url,settingsFile:settingsFile()});
    });
  });
}
